package com.mopick.stylespec;

/**
 * 사진 분석이 실제로 이루어졌는지.
 *
 * <p>이 값이 없으면 "AI가 사진을 보고 아무것도 못 찾았다"와 "AI 호출이 실패했다"를
 * 응답만으로 구분할 수 없다. 둘 다 8필드 NOT_VISIBLE로 보이기 때문이다.
 * 실제로 rate limit(429)로 전부 실패한 응답을 관찰 실패로 오진한 적이 있어 필드로 드러낸다.
 */
public enum AnalysisStatus {
    /** AI가 응답했고 그 결과가 관찰에 반영되었다. */
    OK,
    /** API 키가 없어 분석을 시도하지 않았다. 사용자가 태그를 직접 고르면 된다. */
    AI_DISABLED,
    /** 분석을 시도했으나 재시도 후에도 실패했다. 잠시 후 다시 시도하면 될 수 있다. */
    AI_FAILED
}
